
# İki sayıyı toplar
def toplama(sayi1, sayi2):
    return sayi1 + sayi2


# İki sayıyı birbirinden çıkarır
def cikarma(sayi1, sayi2):
    return sayi1 - sayi2


# İki sayıyı çarpar
def carpma(sayi1, sayi2):
    return sayi1 * sayi2


# İki sayıyı birbirine böler
def bolme(sayi1, sayi2):
    return sayi1 / sayi2
